// Index checks that drizzle's drift check can't make: it compares schema.ts with
// the snapshots, never with a migrated database. Dropping a column drops every
// index that uses it, INCLUDE columns too, with no DROP INDEX in the SQL (0024
// lost two that way), and a hand-written migration can rename what the snapshot
// still calls by its old name.

/**
 * Indexes a migrated database has on purpose although no snapshot lists them,
 * because drizzle can't declare them. Each must still exist after migrating.
 */
export const RAW_INDEXES = {
	// Drizzle 0.45 can't express INCLUDE.
	idx_prompt_runs_admin: "0003: (created_at) INCLUDE (brand_id)",
	// schema-auth.ts is generated by better-auth, which doesn't emit indexes.
	subscription_reference_id_idx: "0012: subscription (reference_id)",
	member_organization_id_user_id_uidx: "0014: member (organization_id, user_id), unique",
};

/** Every index name the snapshot implies: declared indexes, unique constraints and primary keys. */
export function snapshotIndexNames(snapshot) {
	return new Set(Object.values(snapshot.tables).flatMap(tableIndexNames));
}

function tableIndexNames(table) {
	const columns = Object.values(table.columns ?? {});
	return [
		...Object.keys(table.indexes ?? {}),
		...Object.keys(table.uniqueConstraints ?? {}),
		...Object.keys(table.compositePrimaryKeys ?? {}),
		...(columns.some((column) => column.primaryKey) ? [`${table.name}_pkey`] : []),
		...columns
			.filter((column) => column.isUnique)
			.map((column) => column.uniqueName ?? `${table.name}_${column.name}_unique`),
	];
}

/** Indexes the snapshot or RAW_INDEXES promise but the database lacks, and ones it has that neither explains. */
export function snapshotMismatches(snapshotNames, databaseNames) {
	const expected = new Set([...snapshotNames, ...Object.keys(RAW_INDEXES)]);
	return {
		missing: [...expected].filter((name) => !databaseNames.has(name)).sort(),
		unexpected: [...databaseNames].filter((name) => !expected.has(name)).sort(),
	};
}

/**
 * Indexes present before an upgrade and gone after it that the upgrade's own SQL
 * doesn't account for: no DROP INDEX, DROP CONSTRAINT or ALTER INDEX ... RENAME
 * naming it, and no DROP TABLE of its table.
 */
export function unexplainedDrops(before, after, upgradeSql) {
	const sqlText = upgradeSql.join("\n");
	const quoted = (name) => {
		const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
		return String.raw`(?:"${escaped}"|\b${escaped}\b)`;
	};
	return [...before]
		.filter(([name]) => !after.has(name))
		.filter(([name, table]) => {
			const explained = [
				String.raw`DROP\s+INDEX\s+(?:CONCURRENTLY\s+)?(?:IF\s+EXISTS\s+)?(?:"?public"?\.)?${quoted(name)}`,
				String.raw`DROP\s+CONSTRAINT\s+(?:IF\s+EXISTS\s+)?${quoted(name)}`,
				String.raw`ALTER\s+INDEX\s+(?:IF\s+EXISTS\s+)?(?:"?public"?\.)?${quoted(name)}\s+RENAME`,
				String.raw`DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:"?public"?\.)?${quoted(table)}`,
			];
			return !explained.some((pattern) => new RegExp(pattern, "i").test(sqlText));
		})
		.map(([name, table]) => `${table}.${name}`)
		.sort();
}
